using System.Globalization;
using AiSdk.Documents.Resources;

namespace AiSdk.Documents;

/// <summary>Converts a document type to Markdown.</summary>
public interface IDocumentConverter
{
    bool CanConvert(string mediaType);

    Task<DocumentConversionResult> ConvertAsync(DocumentSource source, DocumentConversionContext context, CancellationToken cancellationToken = default);
}

/// <summary>Source of a page's text.</summary>
public enum PageTextSource
{
    /// <summary>Text extracted directly from the file.</summary>
    Text,

    /// <summary>Text recognized with OCR.</summary>
    Ocr,

    /// <summary>Description generated by a vision model.</summary>
    Vision,

    /// <summary>Audio transcript.</summary>
    Transcript,
}

/// <summary>Page, sheet, slide or segment of the converted document.</summary>
public sealed record DocumentPage(int Number, string Markdown, PageTextSource Source = PageTextSource.Text)
{
    /// <summary>Human-readable label (e.g. "Sheet: Sales", "Slide 3", "00:01:30").</summary>
    public string? Label { get; init; }
}

/// <summary>Result of a conversion.</summary>
public sealed record DocumentConversionResult
{
    public required string Markdown { get; init; }

    public required string MediaType { get; init; }

    public string? FileName { get; init; }

    public string? Title { get; init; }

    public IReadOnlyList<DocumentPage> Pages { get; init; } = [];

    public IReadOnlyList<string> Warnings { get; init; } = [];

    /// <summary>Approximate token count of the Markdown (see <see cref="TokenEstimator"/>).</summary>
    public int EstimatedTokens => TokenEstimator.Estimate(Markdown);

    /// <summary>True if any part was obtained with OCR, vision or transcription.</summary>
    public bool UsedAi => Pages.Any(p => p.Source != PageTextSource.Text);

    /// <summary>Creates a result from pages, joining their Markdown.</summary>
    public static DocumentConversionResult FromPages(DocumentSource source, IReadOnlyList<DocumentPage> pages, string? title = null, IReadOnlyList<string>? warnings = null, string separator = "\n\n") =>
        new()
        {
            Markdown = string.Join(separator, pages.Select(p => p.Markdown.Trim()).Where(m => m.Length > 0)),
            MediaType = source.MediaType,
            FileName = source.FileName,
            Title = title,
            Pages = pages,
            Warnings = warnings ?? [],
        };

    /// <summary>
    /// Splits the result into documents for an <see cref="IVectorStore"/>, by page and in chunks of
    /// <paramref name="maxChars"/>. Each chunk carries <c>source</c>, <c>page</c> and <c>title</c>
    /// metadata.
    /// </summary>
    public IReadOnlyList<VectorDocument> ToVectorDocuments(string idPrefix, int maxChars = 1500, int overlap = 150, IReadOnlyDictionary<string, string>? metadata = null)
    {
        var documents = new List<VectorDocument>();
        var pages = Pages.Count > 0 ? Pages : [new DocumentPage(1, Markdown)];
        foreach (var page in pages)
        {
            var chunks = TextChunker.Split(page.Markdown, maxChars, overlap);
            for (var i = 0; i < chunks.Count; i++)
            {
                var meta = new Dictionary<string, string>(metadata ?? new Dictionary<string, string>())
                {
                    ["page"] = page.Number.ToString(System.Globalization.CultureInfo.InvariantCulture),
                };
                if (FileName is not null) meta["source"] = FileName;
                if (Title is not null) meta["title"] = Title;
                if (page.Label is not null) meta["section"] = page.Label;
                documents.Add(new VectorDocument($"{idPrefix}:p{page.Number}:c{i}", chunks[i]) { Metadata = meta });
            }
        }

        return documents;
    }
}

/// <summary>When to apply OCR to the pages of a PDF.</summary>
public enum PdfOcrMode
{
    /// <summary>Only on pages without enough text (scanned pages).</summary>
    Auto,

    /// <summary>Never (embedded text only).</summary>
    Never,

    /// <summary>On every page (useful with OCR models that understand tables and layouts).</summary>
    Always,
}

/// <summary>
/// Progress of a conversion: pages in the document, how many will go through OCR (or vision) and how many of those have
/// finished. Currently reported by the PDF conversion.
/// </summary>
public sealed record DocumentConversionProgress(int Pages, int OcrPages, int OcrPagesDone);

/// <summary>
/// Options for <see cref="MarkdownConverter"/>. The limits (<see cref="MaxInputBytes"/>, <see cref="MaxPdfPages"/>,
/// <see cref="MaxOcrPages"/>, <see cref="MaxNestingDepth"/>...) bound the work a hostile document can cause (memory,
/// CPU, external processes and paid OCR or vision calls); when they are exceeded, part of the document is converted and a
/// warning is added to <see cref="DocumentConversionResult.Warnings"/>, except for <see cref="MaxInputBytes"/>, which
/// throws <see cref="DocumentTooLargeException"/>.
/// </summary>
public sealed class MarkdownConverterOptions
{
    /// <summary>
    /// Maximum size of a document, in bytes (512 MB by default: enough for scanned case files of hundreds of pages). A
    /// larger one throws <see cref="DocumentTooLargeException"/> without being converted.
    /// </summary>
    public long MaxInputBytes { get; init; } = 512L * 1024 * 1024;

    /// <summary>
    /// Maximum nesting depth (128 by default). In HTML, anything deeper is converted to plain text with a warning. In
    /// Word, Excel and PowerPoint, a deeper XML part is rejected with <see cref="InvalidDataException"/>: the Open XML SDK
    /// would load it recursively and a file of a few KB would overflow the process stack.
    /// </summary>
    public int MaxNestingDepth { get; init; } = 128;

    /// <summary>HTML: maximum bytes converted (10 MB by default); the rest is skipped with a warning.</summary>
    public int MaxHtmlBytes { get; init; } = 10 * 1024 * 1024;

    /// <summary>
    /// Maximum characters in each decompressed XML part of Word, Excel and PowerPoint files (32 million by default;
    /// <c>OpenSettings.MaxCharactersInPart</c>). Prevents a small, highly compressed file from taking up gigabytes. A
    /// larger part throws <see cref="InvalidDataException"/>, except Excel sheets, which are read up to that point.
    /// </summary>
    public long MaxOfficePartChars { get; init; } = 32_000_000;

    /// <summary>PDF: maximum pages processed (2000 by default); the rest are skipped with a warning.</summary>
    public int MaxPdfPages { get; init; } = 2000;

    /// <summary>
    /// Maximum pages or images of a document sent to OCR or to the vision model (1000 by default): scanned pages of a PDF
    /// and images embedded in Word, PowerPoint and PDF files. The rest are skipped with a warning. Bounds the OCR processes
    /// and calls a hostile document can cause (completely blank pages, with no text, images or drawings, never go to OCR).
    /// Consider lowering it when using a paid vision model. With an OCR that reads the whole PDF (Mistral OCR), all of its
    /// pages count.
    /// </summary>
    public int MaxOcrPages { get; init; } = 1000;

    /// <summary>
    /// Maximum time for the OCR of a PDF's pages (no limit by default). When it elapses, the remaining pages are left
    /// unrecognized and the result carries a warning saying how many were read: a long document read in part is better
    /// than a cancelled conversion with nothing. Set it below the maximum time the application allows for a conversion.
    /// </summary>
    public TimeSpan? MaxOcrDuration { get; init; }

    /// <summary>
    /// Maximum length of the longer side, in pixels, of a PDF page rasterized for OCR (5000 by default). Pages are
    /// rasterized at 200 DPI; a huge page is rasterized at a lower resolution so as not to exceed this size. Embedded
    /// images larger than this size squared (in pixels) are ignored.
    /// </summary>
    public int MaxRasterPixels { get; init; } = 5000;

    /// <summary>OCR engine for images, scanned pages and embedded images.</summary>
    public IOcrEngine? Ocr { get; init; }

    /// <summary>Vision model used to describe images, charts and video frames.</summary>
    public ILanguageModel? VisionModel { get; init; }

    /// <summary>
    /// Instruction used to describe images with <see cref="VisionModel"/>. By default, a built-in instruction in the
    /// language of <see cref="CultureInfo.CurrentUICulture"/> when the image is described (English, or Spanish for "es*").
    /// </summary>
    public string ImageDescriptionPrompt
    {
        get => field ?? Strings.Vision_ImageDescriptionPrompt;
        init;
    }

    /// <summary>Transcription model for audio and video.</summary>
    public ITranscriptionModel? Transcription { get; init; }

    /// <summary>Expected ISO-639-1 language (OCR and transcription).</summary>
    public string? Language { get; init; }

    public PdfOcrMode PdfOcr { get; init; } = PdfOcrMode.Auto;

    /// <summary>With <see cref="PdfOcrMode.Auto"/>, minimum number of characters for a page to be considered to have text.</summary>
    public int PdfMinCharsPerPage { get; init; } = 30;

    /// <summary>
    /// PDF page rasterizer for OCR. Defaults to <c>pdftoppm</c> if it is installed. Each scanned page is rasterized and
    /// recognized separately (at most <see cref="MaxConcurrency"/> at a time), so the images are never all in memory at
    /// once; if a page cannot be rasterized, the image embedded in that page is used.
    /// </summary>
    public IPdfRasterizer? PdfRasterizer { get; init; } = PdftoppmRasterizer.TryCreate();

    /// <summary>Maximum rows per spreadsheet (the rest is summarized with a warning).</summary>
    public int MaxRowsPerSheet { get; init; } = 1000;

    public bool IncludeHiddenSheets { get; init; }

    /// <summary>Processes images embedded in Word, PowerPoint and PDF files (OCR and/or description).</summary>
    public bool ProcessEmbeddedImages { get; init; } = true;

    /// <summary>Embedded images smaller than this (bytes) are ignored (icons, bullets...).</summary>
    public int MinEmbeddedImageBytes { get; init; } = 4096;

    /// <summary>Embedded images larger than this (bytes, decompressed) are ignored (20 MB by default).</summary>
    public int MaxEmbeddedImageBytes { get; init; } = 20 * 1024 * 1024;

    /// <summary>Path to <c>ffmpeg</c> (video).</summary>
    public string FfmpegPath { get; init; } = "ffmpeg";

    /// <summary>
    /// Maximum duration of a video analyzed with ffmpeg (1 hour by default): only that initial segment is transcribed and
    /// described, with a warning.
    /// </summary>
    public TimeSpan MaxMediaDuration { get; init; } = TimeSpan.FromHours(1);

    /// <summary>
    /// Runner for the tools launched by the converters (ffmpeg); null uses <see cref="ExternalProcess.Runner"/>. The OCR
    /// engine and the rasterizer receive their own in their constructors.
    /// </summary>
    public IExternalProcessRunner? ProcessRunner { get; init; }

    /// <summary>Interval between analyzed video frames.</summary>
    public TimeSpan VideoFrameInterval { get; init; } = TimeSpan.FromSeconds(10);

    public int MaxVideoFrames { get; init; } = 30;

    /// <summary>Parallel OCR / vision calls.</summary>
    public int MaxConcurrency { get; init; } = 4;

    /// <summary>
    /// Download of attachments by URL (<see cref="MarkdownConverter.ConvertAsync(ContentPart, bool, CancellationToken)"/> and
    /// <see cref="AttachmentConversionOptions.DownloadUrls"/>): http/https only, no private networks, with bounded size,
    /// time and redirects (see <see cref="UrlDownloadOptions"/>).
    /// </summary>
    public UrlDownloadOptions UrlDownload { get; init; } = new();

    /// <summary>Receives the conversion progress (e.g. for a progress bar). Invoked from multiple threads.</summary>
    public IProgress<DocumentConversionProgress>? Progress { get; init; }
}

/// <summary>Context received by the converters: options and shared AI services.</summary>
public sealed class DocumentConversionContext(MarkdownConverterOptions options, MarkdownConverter converter)
{
    private int _imageAnalyses;
    private int _imageAnalysesSkipped;
    private int _oversizedImages;

    public MarkdownConverterOptions Options { get; } = options;

    /// <summary>Main converter (for nested documents).</summary>
    public MarkdownConverter Converter { get; } = converter;

    public bool CanAnalyzeImages => Options.Ocr is not null || Options.VisionModel is not null;

    /// <summary>Pages or images that can still be sent to OCR or vision in this document (see <see cref="MarkdownConverterOptions.MaxOcrPages"/>).</summary>
    public int RemainingImageAnalyses => Math.Max(0, Options.MaxOcrPages - Volatile.Read(ref _imageAnalyses));

    /// <summary>Pages or images that were not analyzed because they exceeded <see cref="MarkdownConverterOptions.MaxOcrPages"/>.</summary>
    public int ImageAnalysesSkipped => Volatile.Read(ref _imageAnalysesSkipped);

    /// <summary>
    /// Reserves up to <paramref name="count"/> analyses (OCR or vision) from the document's maximum and returns how many were
    /// granted; the rest are counted in <see cref="ImageAnalysesSkipped"/>. Thread-safe.
    /// </summary>
    public int ReserveImageAnalyses(int count = 1)
    {
        if (count <= 0)
        {
            return 0;
        }

        while (true)
        {
            var used = Volatile.Read(ref _imageAnalyses);
            var granted = Math.Clamp(Options.MaxOcrPages - used, 0, count);
            if (Interlocked.CompareExchange(ref _imageAnalyses, used + granted, used) == used)
            {
                if (granted < count)
                {
                    Interlocked.Add(ref _imageAnalysesSkipped, count - granted);
                }

                return granted;
            }
        }
    }

    /// <summary>Warning for results with analyses skipped because of <see cref="MarkdownConverterOptions.MaxOcrPages"/>; null if there were none.</summary>
    public string? ImageAnalysisLimitWarning() =>
        ImageAnalysesSkipped == 0
            ? null
            : string.Format(CultureInfo.CurrentCulture, Strings.Ocr_MaxPagesReached, ImageAnalysesSkipped, Options.MaxOcrPages);

    /// <summary>Images not sent to OCR because they exceeded <see cref="MarkdownConverterOptions.MaxRasterPixels"/> squared.</summary>
    public int OversizedImagesSkipped => Volatile.Read(ref _oversizedImages);

    /// <summary>Warning for images skipped because of their size in pixels; null if there were none.</summary>
    public string? OversizedImageWarning() =>
        OversizedImagesSkipped == 0
            ? null
            : string.Format(CultureInfo.CurrentCulture, Strings.Ocr_OversizedImages, OversizedImagesSkipped, Options.MaxRasterPixels);

    /// <summary>
    /// OCR of an image or document; null if no engine is configured or if the image exceeds
    /// <see cref="MarkdownConverterOptions.MaxRasterPixels"/> squared (the size is read from the header, without decoding it).
    /// </summary>
    public async Task<OcrResult?> OcrAsync(byte[] data, string mediaType, CancellationToken cancellationToken)
    {
        if (Options.Ocr is not { } ocr || !ocr.Supports(mediaType))
        {
            return null;
        }

        if (mediaType.StartsWith("image/", StringComparison.Ordinal)
            && ImageHeader.TryGetSize(data, out var width, out var height)
            && (long)width * height > (long)Options.MaxRasterPixels * Options.MaxRasterPixels)
        {
            Interlocked.Increment(ref _oversizedImages);
            return null;
        }

        return await ocr.RecognizeAsync(new OcrRequest { Data = data, MediaType = mediaType, Language = Options.Language }, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>Description of an image with the vision model; null if no model is configured.</summary>
    public async Task<string?> DescribeImageAsync(byte[] data, string mediaType, string? instructions, CancellationToken cancellationToken)
    {
        if (Options.VisionModel is not { } model)
        {
            return null;
        }

        var result = await Ai.GenerateTextAsync(new GenerateTextOptions
        {
            Model = model,
            Messages = [ModelMessage.User(new TextPart(instructions ?? Options.ImageDescriptionPrompt), ImagePart.FromBytes(data, mediaType))],
            CancellationToken = cancellationToken,
        }).ConfigureAwait(false);
        return result.Text.Trim();
    }

    /// <summary>
    /// Analyzes an image with whatever is configured: the vision model if there is one (it describes the image and includes
    /// the text) or, otherwise, OCR. Returns null if nothing is configured.
    /// </summary>
    public async Task<(string Markdown, PageTextSource Source)?> AnalyzeImageAsync(byte[] data, string mediaType, CancellationToken cancellationToken)
    {
        if (Options.VisionModel is not null)
        {
            var description = await DescribeImageAsync(data, mediaType, null, cancellationToken).ConfigureAwait(false);
            return (description ?? string.Empty, PageTextSource.Vision);
        }

        var ocr = await OcrAsync(data, mediaType, cancellationToken).ConfigureAwait(false);
        return ocr is null ? null : (ocr.Markdown, PageTextSource.Ocr);
    }
}

/// <summary>The document exceeds <see cref="MarkdownConverterOptions.MaxInputBytes"/> (or a download's maximum) and is not converted.</summary>
public sealed class DocumentTooLargeException : AiSdkException
{
    public DocumentTooLargeException(long size, long limit, string? fileName = null)
        : base(fileName is null
            ? string.Format(CultureInfo.CurrentCulture, Strings.Conversion_DocumentTooLarge, size, limit)
            : string.Format(CultureInfo.CurrentCulture, Strings.Conversion_NamedDocumentTooLarge, fileName, size, limit))
    {
        Size = size;
        Limit = limit;
        FileName = fileName;
    }

    /// <summary>Size of the document in bytes (or what was read until the maximum was exceeded).</summary>
    public long Size { get; }

    /// <summary>Maximum allowed, in bytes.</summary>
    public long Limit { get; }

    public string? FileName { get; }
}
